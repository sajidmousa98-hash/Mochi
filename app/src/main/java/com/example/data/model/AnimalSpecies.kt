enum class AnimalRarity(val label: String, val badgeColor: Long) {
  COMMON("Common", 0xFF81C784),
  UNCOMMON("Uncommon", 0xFF64B5F6),
  RARE("Rare", 0xFFBA68C8),
  LEGENDARY("Legendary", 0xFFFFB300)
}

enum class AnimalCategory(val label: String) {
  PETS("Pets"),
  WOODLAND("Woodland"),
  AQUATIC("Aquatic"),
  FARM_EXOTIC("Sanctuary Pals"),
  FANTASY("Mythical")
}

data class AnimalSpecies(
  val id: String,
  val name: String,
  val category: AnimalCategory,
  val rarity: AnimalRarity,
  val bio: String,
  val personality: String,
  val favoriteFood: String,
  val habitatPreference: String,
  val primaryColor: Long,
  val secondaryColor: Long,
  val cheekColor: Long = 0xFFFFAEB9,
  val eyeColor: Long = 0xFF3E2723,
  val earShape: EarShape = EarShape.ROUND,
  val hasMuzzle: Boolean = false,
  val hasBeak: Boolean = false,
  val hasWhiskers: Boolean = false,
  val hasShell: Boolean = false,
  val specialTrail: String = "hearts",
  val unlockLevel: Int = 1
)

